#!/usr/bin/env python3
"""Build the beacon's replay table from the HAB-1 flight log of 31 Oct 2026.

Input: the Pi's 1 Hz hab1d logs (read only), pulled from the flight card.
  "tap" records carry the beacon's GPS fix (lat, lon, alt_gps, utc).
  "baro_out" records carry the outside pressure and temperature.
Output: firmware/hab_node/replay_data.h, one sample every STEP_S seconds from
60 s before release to 60 s after touchdown.

Release 07:07:06Z and touchdown 09:11:45Z come from
BosconSpace hab1-launch/docs/10-flight-report.md (measured).

usage: tools/make_replay.py <boot-0027 log dir> [step_s]
"""
import bisect, datetime as dt, glob, json, os, sys

RELEASE = dt.datetime(2026, 10, 31, 7, 7, 6, tzinfo=dt.timezone.utc)
TOUCHDOWN = dt.datetime(2026, 10, 31, 9, 11, 45, tzinfo=dt.timezone.utc)
PAD_S, OUT = 60, os.path.join(os.path.dirname(__file__), "..", "firmware", "hab_node", "replay_data.h")


def load(logdir):
    taps, baros = [], []
    for f in sorted(glob.glob(os.path.join(logdir, "hab1d-0*.ndjson"))):
        for line in open(f):
            if '"kind":"tap"' in line:
                r = json.loads(line)
                if r.get("nav") == 3 and r.get("lat"):
                    t = dt.datetime.strptime(r["utc"], "%Y%m%d%H%M%S").replace(tzinfo=dt.timezone.utc)
                    taps.append((t.timestamp(), r["lat"], r["lon"], r["alt_gps"]))
            elif '"kind":"baro_out"' in line:
                r = json.loads(line)
                if r.get("crc_ok"):
                    baros.append((r["wall_ms"] / 1000.0, r["pa"], r["c"]))
    taps.sort(); baros.sort()
    return taps, baros


def nearest(rows, t):
    keys = [r[0] for r in rows]
    i = bisect.bisect_left(keys, t)
    best = min((j for j in (i - 1, i) if 0 <= j < len(rows)), key=lambda j: abs(rows[j][0] - t))
    return rows[best], abs(rows[best][0] - t)


def main():
    logdir = sys.argv[1]
    step = int(sys.argv[2]) if len(sys.argv) > 2 else 60
    taps, baros = load(logdir)
    t0, t1 = RELEASE.timestamp() - PAD_S, TOUCHDOWN.timestamp() + PAD_S
    rows, worst_gps, worst_baro = [], 0, 0
    t = t0
    while t <= t1:
        g, dg = nearest(taps, t)
        b, db = nearest(baros, t)
        worst_gps, worst_baro = max(worst_gps, dg), max(worst_baro, db)
        rows.append((int(round(t - RELEASE.timestamp())), round(g[1] * 1e7), round(g[2] * 1e7),
                     int(round(g[3])), int(round(b[1] / 10)), int(round(b[2] * 100))))
        t += step
    peak = max(rows, key=lambda r: r[3])
    with open(OUT, "w") as f:
        f.write("// Generated by tools/make_replay.py from the HAB-1 flight log, 31 Oct 2026. Do not edit.\n")
        f.write(f"// {len(rows)} samples, one every {step} s, from {PAD_S} s before release to {PAD_S} s after touchdown.\n")
        f.write(f"// Largest gap to the nearest GPS fix {worst_gps:.0f} s, to the nearest outside-baro reading {worst_baro:.1f} s.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("struct ReplaySample { int16_t flightS; int32_t lat7, lon7; uint16_t altM, pressDhPa; int16_t tempCc; };\n")
        f.write(f"#define REPLAY_STEP_S {step}\n#define REPLAY_COUNT {len(rows)}\n")
        f.write("static const ReplaySample REPLAY[REPLAY_COUNT] = {\n")
        for r in rows:
            f.write("  {%d, %d, %d, %d, %d, %d},\n" % r)
        f.write("};\n")
    print(f"{len(rows)} samples every {step} s -> {os.path.normpath(OUT)}")
    print(f"peak sample: {peak[3]} m at flight time {peak[0]} s; worst gaps: gps {worst_gps:.0f} s, baro {worst_baro:.1f} s")


if __name__ == "__main__":
    main()
